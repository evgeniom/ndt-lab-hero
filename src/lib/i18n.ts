const KEY = "ndt-portal-lang";
export function useLang() {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => { const s = localStorage.getItem(KEY) as Lang | null; if (s && LANGS.includes(s)) setLangState(s); }, []);
  const setLang = (l: Lang) => { localStorage.setItem(KEY, l); setLangState(l); };
  return { lang, setLang, t: D[lang] };
}
